VOICES = [W, M, B]

def gq(lid, i, sentence, zh, options, answer, expl, suffix='a'):
    return q(f'{lid}-{i}{suffix}', f'{lid}-{i}', '選出正確答案', options, answer, expl, sentence=sentence, zh=zh)

def glesson(lid, title, titleEn, summary, concept, explain_body, table, tip, examples, breakdown, contrast, practice, similar, extension, minutes=15):
    ex_items = [{'en': en, 'zh': zh, 'highlight': hl, 'audio': say(f'assets/audio/lessons/{lid}/ex{i + 1}.mp3', en, VOICES[i % 3])}
                for i, (en, zh, hl) in enumerate(examples)]
    lesson({
        'id': lid, 'world': 'grammar', 'order': 0, 'type': 'grammar', 'title': title, 'titleEn': titleEn, 'summary': summary, 'minutes': minutes,
        'steps': [
            {'kind': 'concept', 'title': '中文概念', 'body': concept},
            {'kind': 'explain', 'title': '簡單說明', 'body': explain_body, 'table': {'head': table[0], 'rows': table[1]}, 'tip': tip},
            {'kind': 'examples', 'title': '英文例句', 'items': ex_items},
            {'kind': 'breakdown', 'title': '句子拆解', 'items': [{'parts': [{'text': t, 'label': l} for t, l in parts], 'zh': zh} for parts, zh in breakdown]},
            {'kind': 'contrast', 'title': '正確與錯誤示範', 'items': [{'wrong': w, 'right': r, 'why': y} for w, r, y in contrast]},
            {'kind': 'practice', 'title': '互動練習', 'intro': '選出正確答案。答錯會再出一題類似的。',
             'questions': [gq(lid, i, *x) for i, x in enumerate(practice)],
             'similar': [gq(lid, i, *x, suffix='b') for i, x in enumerate(similar)]},
            {'kind': 'review', 'title': '答案解析'},
            {'kind': 'practice', 'title': '延伸練習：多益實戰', 'intro': '多益 Part 5 的出題方式，挑戰看看。',
             'questions': [q(f'{lid}-x{i}', f'{lid}-x{i}', '多益實戰：選出最適合的答案', o, a, e, sentence=s, zh=z) for i, (s, z, o, a, e) in enumerate(extension)]},
        ]})

